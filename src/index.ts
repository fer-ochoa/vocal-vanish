// HTTP helpers (Node's https module — no extra dependencies).
// ---------------------------------------------------------------------------

function httpGetJson<T>(url: string): Promise<T> {
  return new Promise((resolve, reject) => {
    const req = https.get(
      url,
      { headers: { "User-Agent": "vocal-vanish/1.0" } },
      (res) => {
        if (
          !res.statusCode ||
          (res.statusCode >= 300 && res.statusCode < 400)
        ) {
          // Follow a single redirect (e.g. /api/karas/{kid}/hardsub -> /hardsubs/*.mp4)
          const loc = res.headers.location;
          res.resume();
          if (loc) {
            httpGetJson<T>(new URL(loc, url).toString()).then(resolve, reject);
            return;
          }
        }
        if (!res.statusCode || res.statusCode >= 400) {
          const err = new Error(`HTTP ${res.statusCode} for ${url}`);
          res.resume();
          reject(err);
          return;
        }
        let body = "";
        res.setEncoding("utf8");
        res.on("data", (chunk) => (body += chunk));
        res.on("end", () => {
          try {
            resolve(JSON.parse(body) as T);
          } catch (e) {
            reject(
              new Error(`Invalid JSON from ${url}: ${(e as Error).message}`),
            );
          }
        });
      },
    );
    req.on("error", reject);
  });
}

/**
 * Stream a file download to disk, reporting progress. Returns the final file
 * size in bytes. Throws on HTTP error or network failure.
 */
function downloadFile(
  url: string,
  destPath: string,
  onProgress: (received: number, total: number | null) => void,
): Promise<number> {
  return new Promise((resolve, reject) => {
    const req = https.get(
      url,
      { headers: { "User-Agent": "vocal-vanish/1.0" } },
      (res) => {
        // Follow redirects transparently.
        if (
          res.statusCode &&
          res.statusCode >= 300 &&
          res.statusCode < 400 &&
          res.headers.location
        ) {
          res.resume();
          const next = new URL(res.headers.location, url).toString();
          downloadFile(next, destPath, onProgress).then(resolve, reject);
          return;
        }
        if (!res.statusCode || res.statusCode >= 400) {
          res.resume();
          reject(new Error(`HTTP ${res.statusCode} downloading ${url}`));
          return;
        }
        const total = res.headers["content-length"]
          ? parseInt(res.headers["content-length"], 10)
          : null;
        let received = 0;
        const out = fs.createWriteStream(destPath);
        res.on("data", (chunk: Buffer) => {
          received += chunk.length;
          onProgress(received, total);
        });
        res.pipe(out);
        out.on("error", reject);
        out.on("finish", () => resolve(received));
      },
    );
    req.on("error", reject);
  });
}

