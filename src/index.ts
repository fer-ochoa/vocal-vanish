/**
 * Electron applies a restrictive default CSP (`default-src 'self' 'unsafe-inline' data:`)
 * that blocks the `blob:` media URLs we use to play downloaded videos. We set an
 * explicit, appropriate policy on the session instead: media is allowed from blob:
 * and file:, while scripts stay locked to 'self' in production.
 *
 * In development, webpack-dev-server's HMR client evaluates its code via `eval`,
 * so we relax script-src to allow 'unsafe-eval' (and inline) — otherwise the app
 * shows a black screen. This relaxation is dev-only; production keeps the strict
 * 'self' script policy.
 */
function applyCsp(): void {
  const isDev = !app.isPackaged;
  const csp = [
    "default-src 'self'",
    isDev
      ? "script-src 'self' 'unsafe-inline' 'unsafe-eval'"
      : "script-src 'self'",
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "media-src 'self' blob: file:",
    "font-src 'self' data:",
    "connect-src 'self' blob: https://kara.moe https://huggingface.co https://*.hf.co https://*.huggingface.co",
  ].join("; ");

  session.defaultSession.webRequest.onHeadersReceived((details, callback) => {
    callback({
      responseHeaders: {
        ...details.responseHeaders,
        "Content-Security-Policy": [csp],
        "Cross-Origin-Opener-Policy": ["same-origin"],
        "Cross-Origin-Embedder-Policy": ["require-corp"],
      },
    });
  });
}

